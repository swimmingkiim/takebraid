def test_actual_artifact_scoring_matches_independent_oracle_cache_force_and_cli(dataset, tmp_path):
    path, _, source = dataset
    original = source.read_bytes()
    result = evaluate_manifest(path, tmp_path / "evaluation")
    report = json.loads(result.read_text())
    assert report["evidence_scope"] == "synthetic_only"
    assert report["automatic_exclusion_validated"] is False
    score = report["entries"][0]["score"]
    assert score["ratios"]["precision"] == {"numerator": 1, "denominator": 2}
    assert score["ratios"]["recall_all_labeled_defect"] == {"numerator": 1, "denominator": 3}
    assert score["durations"]["excluded_normal_seconds"] == {"numerator": 1, "denominator": 25}
    assert score["ratios"]["normal_exclusion_rate"] == {"numerator": 1, "denominator": 2}
    assert score["disagreement_frames"] == 1
    assert len(report["cohorts"]) == 1 and report["cohorts"][0]["kind"] == "synthetic"
    assert evaluate_manifest(path, tmp_path / "evaluation") == result
    assert evaluate_manifest(path, tmp_path / "evaluation", force=True) != result
    assert source.read_bytes() == original
    assert main(["evaluate", str(path), "--output", str(tmp_path / "evaluation")]) == 0


@pytest.mark.parametrize("group", ["project_id", "shoot_id", "asset_id"])
def test_manifest_rejects_declared_split_leakage_before_scoring(dataset, group):
    path, manifest, _ = dataset
    other = copy.deepcopy(manifest["entries"][0])
    other.update(id="calibration", split="calibration")
    if group != "project_id":
        other["project_id"] = "other-project"
    if group == "asset_id":
        other["shoot_id"] = "other-shoot"
    manifest["entries"].append(other)
    path.write_text(json.dumps(manifest))
    with pytest.raises(ValueError, match=f"Split leakage: {group}"):
        load_manifest(path)


@pytest.mark.parametrize("change", ["permission", "policy", "votes", "partition", "camera-method"])
def test_invalid_rights_protocol_or_labels_are_not_scored(dataset, tmp_path, change):
    path, manifest, _ = dataset
    entry = manifest["entries"][0]
    if change == "permission":
        entry["rights"]["evaluation_permitted"] = False
    elif change == "policy":
        manifest["policy_registry"]["exposure_failure"] = "0" * 64
    elif change == "votes":
        entry["labels"][0]["votes"].pop("fixture-b")
    elif change == "partition":
        entry["labels"].pop()
    else:
        entry["kind"] = "camera"
    path.write_text(json.dumps(manifest))
    with pytest.raises(ValueError):
        evaluate_manifest(path, tmp_path / "evaluation")


@pytest.mark.parametrize(
    "error,state", [(ValueError("score failure"), "failed"), (KeyboardInterrupt(), "cancelled")]
)
def test_scoring_failure_and_cancellation_keep_terminal_receipts(
    dataset, tmp_path, monkeypatch, error, state
):
    path, _, _ = dataset

    def fail(*args, **kwargs):
        raise error

    monkeypatch.setattr("takebraid.application.evaluation.score_labels", fail)
    output = tmp_path / "evaluation"
    with pytest.raises(type(error)):
        evaluate_manifest(path, output)
    receipts = [json.loads(p.read_text()) for p in output.glob("stages/*/attempts/*/receipt.json")]
    assert len(receipts) == 1 and receipts[0]["status"] == state
    assert not list(output.glob("stages/*/completed.json"))


def test_label_mutation_and_cache_corruption_are_rejected(dataset, tmp_path, monkeypatch):
    from takebraid.application import evaluation

    path, _, _ = dataset
    output = tmp_path / "evaluation"
    report = evaluate_manifest(path, output)
    report.write_text("{}")
    with pytest.raises(ValueError, match="checksum"):
        evaluate_manifest(path, output)
    original = evaluation.score_labels

    def mutate(*args, **kwargs):
        result = original(*args, **kwargs)
        path.write_text(path.read_text() + " ")
        return result

    monkeypatch.setattr(evaluation, "score_labels", mutate)
    with pytest.raises(ValueError, match="changed during"):
        evaluate_manifest(path, output, force=True)


@pytest.mark.parametrize(
    "method,count,accepted",
    [
        ("human", 1, False),
        ("human", 2, True),
        ("assistant_review", 1, True),
        ("assistant_review", 2, False),
    ],
)
def test_declared_review_levels_preserve_human_validation_requirements(
    dataset, tmp_path, method, count, accepted
):
    # Generated signals simulate metadata contracts here; this is not camera evidence.
    path, manifest, _ = dataset
    entry = manifest["entries"][0]
    entry.update(
        kind="camera",
        label_method=method,
        annotators=[f"review-{i}" for i in range(count)],
        annotation_protocol="Generated signal contract test; not real camera annotation",
    )
    for label in entry["labels"]:
        original = set(label["votes"].values())
        value = next(iter(original)) if len(original) == 1 else "unknown"
        label["votes"] = {rater: value for rater in entry["annotators"]}
    path.write_text(json.dumps(manifest))
    if not accepted:
        with pytest.raises(ValueError):
            evaluate_manifest(path, tmp_path / "review-evaluation")
    else:
        output = evaluate_manifest(path, tmp_path / "review-evaluation")
        report = json.loads(output.read_text())
        assert report["review_levels"] == [method]
        assert all(c["label_method"] == method for c in report["cohorts"])
        assert report["automatic_exclusion_validated"] is False
        assert report["evidence_scope"] == (
            "camera_assistant_review_only" if method == "assistant_review" else "camera_only"
        )


def test_one_constructed_oracle_is_not_mislabeled_as_two_humans(dataset, tmp_path):
    path, manifest, _ = dataset
    entry = manifest["entries"][0]
    entry["annotators"] = ["single-constructed-oracle"]
    for label in entry["labels"]:
        values = set(label["votes"].values())
        label["votes"] = {
            "single-constructed-oracle": next(iter(values)) if len(values) == 1 else "unknown"
        }
